let currentLang = "pt";

// Traduz uma chave. Funções recebem os argumentos extras; textos trocam {variáveis}.
function t(key, ...args) {
    const dict = I18N[currentLang] || I18N.pt;
    let value = dict[key];

    if (value === undefined) value = I18N.pt[key];
    if (value === undefined) return key;

    if (typeof value === "function") return value(...args);

    if (typeof value === "string" && args[0] && typeof args[0] === "object") {
        return value.replace(/\{(\w+)\}/g, (_, name) => args[0][name] ?? "");
    }

    return value;
}

function currentLocale() {
    return (I18N[currentLang] || I18N.pt)._locale;
}

// Aplica as traduções em elementos marcados no HTML
function applyStaticTranslations(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });

    document.documentElement.lang = currentLocale();
}
